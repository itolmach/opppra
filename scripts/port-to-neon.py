#!/usr/bin/env python3
"""Rewrites the Supabase migrations as Neon migrations.

Generated rather than hand-copied so the two can be diffed and the port
re-checked whenever a Supabase migration changes. Run from the repo root:

    python3 scripts/port-to-neon.py

Almost nothing changes. Neon's Data API validates Managed Better Auth JWTs
and exposes auth.uid() returning uuid -- the same name and return type
Supabase used -- so all 26 row level security policies survive byte for byte.
Only the three substitutions below are needed, and the script fails loudly if
it finds a Supabase-only object it does not know how to port, rather than
emitting SQL that would not run.

0002_storage.sql is skipped on purpose: it is Supabase Storage buckets and
policies, which Neon Object Storage replaces with a different mechanism
(S3-compatible buckets and presigned URLs). See neon/migrations/README.md.
"""
import io, os, re, sys

SRC, DST = 'supabase/migrations', 'neon/migrations'
SKIP = ('0002',)

HEADER = """-- Ported from {src} for Neon. Generated by scripts/port-to-neon.py --
-- do not edit by hand; edit the Supabase migration and re-run the script.
--
-- Neon's Data API exposes auth.uid() returning uuid, the same name and type
-- Supabase used, so every row level security policy below is unchanged.
-- To see exactly what changed, diff this against {src}.

"""

# No substitution may add a trailing `-- comment`. These fire inside column
# definitions, where everything after `--` to end of line is swallowed: the
# first attempt turned `references auth.users (id) on delete cascade,` into a
# column with no delete rule and no comma, and the SQL no longer parsed. What
# changed is recorded in the header and visible with
#     diff supabase/migrations/0001_init.sql neon/migrations/0001_init.sql
SUBS = [
    # Users live in Better Auth's own table, inside our own database, so the
    # foreign keys and the signup trigger still work -- they just point
    # somewhere else.
    (r'references\s+auth\.users\s*\(\s*id\s*\)',
     'references neon_auth."user" (id)'),
    # The signup trigger cannot come across at all: neon_auth."user" is
    # Neon-managed, and opera_owner has SELECT and REFERENCES on it but not
    # TRIGGER, so `create trigger ... on neon_auth."user"` is refused. The
    # function and trigger are cut here and replaced by an idempotent RPC in
    # neon/migrations/0006_neon_user_bootstrap.sql, which the client calls
    # once after sign-in.
    (r'(?s)-- Auto-create a profile row.*?execute function public\.handle_new_user\(\);\n',
     '-- NOTE: the Supabase signup trigger that created a profile and the two\n'
     '-- default lists is not here. See 0006_neon_user_bootstrap.sql.\n'),
    # Better Auth keeps the display name in a column rather than a JSON blob.
    (r"coalesce\(new\.raw_user_meta_data\s*->>\s*'display_name',\s*null\)",
     "nullif(new.name, '')"),
    # Comments that would now point at a table that does not exist here.
    (r'1:1 with auth\.users', '1:1 with neon_auth."user"'),
]

# Supabase-only objects this script cannot port. Hitting one means the SQL
# would fail on Neon, so stop rather than write it out.
UNPORTABLE = re.compile(r'\bauth\.(users|role)\b|\bstorage\.\w+|\bsupabase_\w+')

def main():
    os.makedirs(DST, exist_ok=True)
    failures = []
    for name in sorted(os.listdir(SRC)):
        if not name.endswith('.sql') or name.startswith(SKIP):
            continue
        text = io.open(os.path.join(SRC, name), encoding='utf-8').read()
        for pattern, replacement in SUBS:
            text = re.sub(pattern, replacement, text)
        # Check the SQL, not the commentary: the NEON: markers above name
        # the Supabase objects they replaced, and would match every time.
        code = re.sub(r'--[^\n]*', '', text)
        left = {m.group(0) for m in UNPORTABLE.finditer(code)}
        if left:
            failures.append(f'{name}: {", ".join(sorted(left))}')
        io.open(os.path.join(DST, name), 'w', encoding='utf-8').write(
            HEADER.format(src=f'{SRC}/{name}') + text)
        print(f'  wrote {DST}/{name}')
    if failures:
        print('\nSupabase-only objects this script cannot port:', file=sys.stderr)
        for f in failures:
            print(f'  {f}', file=sys.stderr)
        sys.exit(1)
    print('\nPorted cleanly. 0002_storage.sql skipped (Neon Object Storage replaces it).')

main()
